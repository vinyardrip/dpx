# -----------------------------------------------------------------
# Translate: t KEY [printf-args...]
# -----------------------------------------------------------------
t() {
    local key="${1:-}"
    [[ -z "$key" ]] && return 1
    shift || true

    local lang="${_DPX_LANG:-en}" msg=""

    if [[ "$lang" == "ru" && -n "${_I18N_RU[$key]:-}" ]]; then
        msg="${_I18N_RU[$key]}"
    elif [[ -n "${_I18N_EN[$key]:-}" ]]; then
        msg="${_I18N_EN[$key]}"
    else
        return 1
    fi

    local out=""
    printf -v out -- "$msg" "$@" 2>/dev/null
    printf '%s\n' "$out"
}

